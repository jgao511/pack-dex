import crypto from "node:crypto";
import { spawn } from "node:child_process";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildScannerCatalog } from "../src/lib/cardScanner/buildScannerCatalog.js";
import { createCachedImageLoader, resolveCatalogImageUrl } from "./build-scanner-visual-index.mjs";

const ROOT_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC_DIR = path.join(ROOT_DIR, "public", "scanner-ai");
const META_PATH = path.join(PUBLIC_DIR, "catalog-embeddings.meta.json");
const CATALOG_META_PATH = path.join(PUBLIC_DIR, "catalog-metadata.json");
const MODEL_PATH = path.join(PUBLIC_DIR, "frozen-a-62f2ff60.tflite");
const GENERATED_MODULE_PATH = path.join(ROOT_DIR, "mobile-app", "src", "lib", "generated", "frozenAScannerManifest.js");
const CACHE_PATH = path.join(ROOT_DIR, "node_modules", ".cache", "packdex-frozen-scanner-index");
const MODEL_SHA256 = "62f2ff60cfdb09714a01fa74343e4dc1968601c2a43046979cbc548c28027c7c";
const DIMENSIONS = 128;
const ROW_BYTES = DIMENSIONS * 2;

function sha256(value) {
  return crypto.createHash("sha256").update(value).digest("hex");
}

function parseArgs(argv) {
  const options = {};
  for (const argument of argv) {
    if (argument === "--check") options.check = true;
    else if (argument === "--reuse-existing") options.reuseExisting = true;
    else {
      const match = argument.match(/^--([^=]+)=(.*)$/);
      if (!match) throw new Error(`Unknown argument ${argument}.`);
      options[match[1]] = match[2];
    }
  }
  return options;
}

async function runProcess(command, args, env = process.env) {
  await new Promise((resolve, reject) => {
    const child = spawn(command, args, { cwd: ROOT_DIR, env, stdio: "inherit", windowsHide: true });
    child.once("error", reject);
    child.once("exit", (code) => code === 0 ? resolve() : reject(new Error(`${command} exited with ${code}.`)));
  });
}

function generatedModule({ vectorFile, vectorSha256, vectorBytes, count }) {
  return `// Generated by scripts/build-frozen-scanner-index.mjs.\n` +
    `export const FROZEN_A_INDEX_FILE = ${JSON.stringify(vectorFile)};\n` +
    `export const FROZEN_A_INDEX_SHA256 = ${JSON.stringify(vectorSha256)};\n` +
    `export const FROZEN_A_INDEX_BYTES = ${vectorBytes};\n` +
    `export const FROZEN_A_CARD_COUNT = ${count};\n` +
    `export const FROZEN_A_DIMENSIONS = ${DIMENSIONS};\n`;
}

async function readExistingRows() {
  const metadata = JSON.parse(await fs.readFile(META_PATH, "utf8"));
  const vectorPath = path.join(PUBLIC_DIR, metadata.vectorFile);
  const vectorBytes = await fs.readFile(vectorPath);
  if (sha256(vectorBytes) !== metadata.vectorSha256 || vectorBytes.length !== metadata.vectorBytes) {
    throw new Error("Existing frozen scanner vector checksum is invalid.");
  }
  if (metadata.dimensions !== DIMENSIONS || vectorBytes.length !== metadata.cardIds.length * ROW_BYTES) {
    throw new Error("Existing frozen scanner tensor contract is invalid.");
  }
  return {
    metadata,
    vectorPath,
    rows: new Map(metadata.cardIds.map((cardId, index) => [cardId, vectorBytes.subarray(index * ROW_BYTES, (index + 1) * ROW_BYTES)])),
  };
}

async function check() {
  const catalogIds = buildScannerCatalog().map((entry) => entry.cardId).sort();
  const existing = await readExistingRows();
  const actualIds = [...existing.metadata.cardIds].sort();
  if (JSON.stringify(catalogIds) !== JSON.stringify(actualIds)) {
    throw new Error(`Frozen scanner index is stale: expected ${catalogIds.length} canonical IDs, found ${actualIds.length}.`);
  }
  const expectedModule = generatedModule({
    vectorFile: existing.metadata.vectorFile,
    vectorSha256: existing.metadata.vectorSha256,
    vectorBytes: existing.metadata.vectorBytes,
    count: existing.metadata.count,
  });
  if (await fs.readFile(GENERATED_MODULE_PATH, "utf8") !== expectedModule) {
    throw new Error("Frozen scanner runtime manifest is stale.");
  }
  console.log(`Frozen scanner index is current: ${catalogIds.length} canonical cards.`);
}

async function build(options) {
  const catalog = buildScannerCatalog().sort((left, right) => left.cardId.localeCompare(right.cardId));
  const existing = options.reuseExisting ? await readExistingRows() : { rows: new Map(), metadata: null };
  const reusedCardCount = catalog.filter((entry) => existing.rows.has(entry.cardId)).length;
  const missing = catalog.filter((entry) => !existing.rows.has(entry.cardId));
  const python = options.python || process.env.PACKDEX_PYTHON;
  const pythonPath = options["python-path"] || process.env.PACKDEX_PYTHONPATH;
  if (missing.length && !python) throw new Error("Provide --python=<path> (and optionally --python-path=<site-packages>) to embed missing cards.");

  await fs.mkdir(CACHE_PATH, { recursive: true });
  const loader = createCachedImageLoader({ cachePath: path.join(CACHE_PATH, "images") });
  const jobs = [];
  for (let index = 0; index < missing.length; index += 1) {
    const entry = missing[index];
    const source = resolveCatalogImageUrl(entry.imageUrl);
    const imagePath = path.join(CACHE_PATH, "jobs", `${crypto.createHash("sha1").update(entry.cardId).digest("hex")}.img`);
    await fs.mkdir(path.dirname(imagePath), { recursive: true });
    await fs.writeFile(imagePath, await loader.load(source));
    jobs.push({ cardId: entry.cardId, imagePath });
    if ((index + 1) % 100 === 0 || index + 1 === missing.length) console.log(`Prepared ${index + 1}/${missing.length} missing images.`);
  }

  const jobsPath = path.join(CACHE_PATH, "jobs.json");
  const embeddedPath = path.join(CACHE_PATH, "embedded.f16");
  await fs.writeFile(jobsPath, JSON.stringify(jobs));
  if (jobs.length) {
    await runProcess(python, [
      path.join(ROOT_DIR, "scripts", "embed-scanner-images.py"),
      `--model=${MODEL_PATH}`,
      `--jobs=${jobsPath}`,
      `--output=${embeddedPath}`,
      `--batch-size=${options["batch-size"] || 32}`,
    ], { ...process.env, ...(pythonPath ? { PYTHONPATH: pythonPath } : {}) });
  } else {
    await fs.writeFile(embeddedPath, Buffer.alloc(0));
  }

  const embedded = await fs.readFile(embeddedPath);
  if (embedded.length !== jobs.length * ROW_BYTES) throw new Error("Embedded vector byte count is invalid.");
  const embeddedRows = new Map(jobs.map((job, index) => [
    job.cardId,
    embedded.subarray(index * ROW_BYTES, (index + 1) * ROW_BYTES),
  ]));
  const output = Buffer.concat(catalog.map((entry) => existing.rows.get(entry.cardId) || embeddedRows.get(entry.cardId)));
  const vectorSha256 = sha256(output);
  const vectorFile = `catalog-embeddings-${vectorSha256.slice(0, 8)}.f16`;
  const vectorPath = path.join(PUBLIC_DIR, vectorFile);
  const catalogMetadataBytes = await fs.readFile(CATALOG_META_PATH);
  const catalogMetadata = JSON.parse(catalogMetadataBytes);
  const cardIds = catalog.map((entry) => entry.cardId);
  const metadata = {
    ...(existing.metadata || {}),
    schemaVersion: 2,
    indexVersion: "packdex-index-20260802-canonical",
    count: cardIds.length,
    dimensions: DIMENSIONS,
    dtype: "float16-le",
    normalized: true,
    vectorFile,
    vectorBytes: output.length,
    vectorSha256,
    cardIds,
    cardIdsSha256: sha256(`${cardIds.join("\n")}\n`),
    metadataFile: path.basename(CATALOG_META_PATH),
    metadataSha256: sha256(catalogMetadataBytes),
    source: { catalogCardsSha256: sha256(JSON.stringify(catalogMetadata.cards)) },
    model: {
      ...(existing.metadata?.model || {}),
      file: path.basename(MODEL_PATH),
      sha256: MODEL_SHA256,
    },
    build: {
      reusedCardCount,
      embeddedCardCount: jobs.length,
      batchSize: Number(options["batch-size"] || 32),
    },
  };
  const temporaryVectorPath = `${vectorPath}.${process.pid}.tmp`;
  const temporaryMetaPath = `${META_PATH}.${process.pid}.tmp`;
  const temporaryModulePath = `${GENERATED_MODULE_PATH}.${process.pid}.tmp`;
  await fs.mkdir(path.dirname(GENERATED_MODULE_PATH), { recursive: true });
  await fs.writeFile(temporaryVectorPath, output);
  await fs.writeFile(temporaryMetaPath, `${JSON.stringify(metadata, null, 2)}\n`);
  await fs.writeFile(temporaryModulePath, generatedModule({ vectorFile, vectorSha256, vectorBytes: output.length, count: cardIds.length }));
  await fs.rename(temporaryVectorPath, vectorPath);
  await fs.rename(temporaryMetaPath, META_PATH);
  await fs.rename(temporaryModulePath, GENERATED_MODULE_PATH);
  console.log(JSON.stringify({ vectorFile, count: cardIds.length, reused: reusedCardCount, embedded: jobs.length, bytes: output.length, sha256: vectorSha256 }, null, 2));
}

const options = parseArgs(process.argv.slice(2));
if (options.check) await check();
else await build(options);
