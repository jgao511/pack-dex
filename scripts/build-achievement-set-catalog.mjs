import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { activeSets } from "../src/data/sets.js";
import {
  getCardCollectionKey,
  getPullableCollectionCards,
} from "../src/utils/collectionStorage.js";

const ROOT_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT_PATH = path.join(
  ROOT_DIR,
  "supabase",
  "functions",
  "check-achievements",
  "setCompletionCatalog.js"
);

const catalog = activeSets
  .map((set) => ({
    setId: String(set.id),
    requiredCardIds: getPullableCollectionCards(set).map((card) => getCardCollectionKey(card, set.id)),
  }))
  .filter((set) => set.requiredCardIds.length > 0);

const output = `// Generated by scripts/build-achievement-set-catalog.mjs.\nexport default ${JSON.stringify(catalog)};\n`;

if (process.argv.includes("--check")) {
  const existing = fs.existsSync(OUTPUT_PATH) ? fs.readFileSync(OUTPUT_PATH, "utf8") : "";
  if (existing !== output) {
    throw new Error("Achievement set-completion catalog is stale. Rebuild it before deployment.");
  }
  console.log(`Achievement set-completion catalog is current: ${catalog.length} active sets.`);
} else {
  fs.writeFileSync(OUTPUT_PATH, output);
  console.log(`Wrote ${catalog.length} active sets to ${OUTPUT_PATH}.`);
}
